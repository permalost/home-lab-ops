#!/usr/bin/env bash
# Regenerate kubernetes/apps/hermes-dev/skills/dev/SKILL.md from the agent-playbook developer
# files, so the Hermes-dev agent and Hobbes follow the same text. Re-run after playbook changes.
#
# Usage: hermes-dev-skill.sh   (PLAYBOOK_DIR=~/code/agent-playbook by default)

set -o errexit
set -o nounset
set -o pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PLAYBOOK="${PLAYBOOK_DIR:-$HOME/code/agent-playbook}"
OUT="$REPO_ROOT/kubernetes/apps/hermes-dev/skills/dev/SKILL.md"
FILES=(agents/developer.md rules.md docs.md lessons.md)

for f in "${FILES[@]}"; do
  [ -f "$PLAYBOOK/$f" ] || { echo "missing $PLAYBOOK/$f" >&2; exit 1; }
done
sha="$(git -C "$PLAYBOOK" rev-parse --short HEAD)"

{
  cat <<EOF
---
name: dev
description: "Implement a task as a pull request on permalost/home-lab-ops from the shaved-monkey fork. The developer rules are the same text the Hobbes agent follows."
version: 0.1.0
prerequisites:
  env_vars: [DEV_GITHUB_USER, DEV_GITHUB_TOKEN]
  commands: [git, curl]
metadata:
  hermes:
    tags: [Development, GitOps, Pull requests]
---

# Developer

Source: wdo/agent-playbook at $sha (agents/developer.md, rules.md, docs.md, lessons.md), unchanged
below the "This pod" section. Generated by scripts/hermes-dev-skill.sh; do not edit by hand.

## This pod

- Read \`\$GITHUB_USER\` as \`\$DEV_GITHUB_USER\` and \`\$GITHUB_TOKEN\` as \`\$DEV_GITHUB_TOKEN\`: Hermes strips
  \`GITHUB_TOKEN\` from terminal commands.
- Work under \`/opt/data/work/<task>\`. Clone your fork with
  \`git clone https://x-access-token:\$DEV_GITHUB_TOKEN@github.com/\$DEV_GITHUB_USER/home-lab-ops.git\`
  and add \`upstream\` (https://github.com/permalost/home-lab-ops.git).
- Commit as \`Jonathon Halvorson <82721715+shaved-monkey@users.noreply.github.com>\` (set \`user.name\` and \`user.email\`).
- This pod has \`git\`, \`curl\` and Python. It has no \`gh\`, \`jq\`, \`task\`, \`kustomize\` or \`kubeconform\`:
  open the PR with \`curl\` on the GitHub API, and list every repo check you could not run under **Not verified**.
- The wake prompt from Paperclip carries the task and the run's execution contract; follow it for comments and status.
EOF
  for f in "${FILES[@]}"; do
    printf '\n\n---\n\n<!-- from %s -->\n\n' "$f"
    cat "$PLAYBOOK/$f"
  done
} > "$OUT"

# Flux substitutes dollar-brace placeholders inside ConfigMaps.
if grep -q '\${' "$OUT"; then
  echo "refusing: $OUT contains a dollar-brace placeholder" >&2
  rm -f "$OUT"
  exit 1
fi
echo "wrote $OUT ($(wc -c < "$OUT") bytes, playbook $sha)"
